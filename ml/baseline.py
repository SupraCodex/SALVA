"""Scientific baseline: how good is the kinetic model?  (asked BEFORE 'is LightGBM better?')

IMPORTANT interpretation: the labels are produced by the kinetic model itself, so the
baseline is "perfect" up to the irreducible lot-to-lot variability that no model can see.
Its numbers describe the SYNTHETIC world, not reality.  Real-world validation: NOT DONE.

    python -m ml.baseline --split ml/artifacts/splits/<split_dir>
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import pandas as pd
from salva_core.loss_model.kinetic_model import KineticLossModel
from salva_core.params import load_product

from . import metrics as M
from .config import load_config, load_yaml, write_json
from .split import load_split


def evaluate_baseline(splits: dict[str, pd.DataFrame], cfg: dict[str, Any], gate: dict[str, Any]) -> dict[str, Any]:
    params = load_product(cfg["product"])
    model = KineticLossModel(params)
    out: dict[str, Any] = {
        "model": model.version,
        "note": ("Labels are generated by this very model; metrics measure irreducible lot "
                 "variability in a SYNTHETIC world, not accuracy on real produce."),
        "real_world_validation": "NOT PERFORMED",
    }
    for name in ("val", "test", "test_extrapolated"):
        out[name] = M.distribution_metrics(model, splits[name])
    out["monotonicity"] = M.monotonicity_violations(model, params, splits["test"], gate["monotonicity"])
    out["latency"] = M.latency_ms(model, splits["test"], gate["latency"]["n_rows"], gate["latency"]["repeats"])
    return out


def run(split_dir: Path | str, config: Path | str | None = None) -> Path:
    cfg = load_config(config)
    gate = load_yaml(Path(__file__).parent / "params" / "go_nogo.yaml")
    result = evaluate_baseline(load_split(split_dir), cfg, gate)
    path = Path(split_dir) / "baseline_metrics.json"
    write_json(path, result)
    return path


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Kinetic baseline metrics")
    ap.add_argument("--split", required=True)
    ap.add_argument("--config", default=None)
    a = ap.parse_args(argv)
    path = run(a.split, a.config)
    r = __import__("json").loads(path.read_text())
    t = r["test"]
    print(f"Kinetic baseline ({r['model']}) on TEST: P50 MAE vs realised={t['mae_p50_vs_realised']:.4f} "
          f"coverage P10-P90={t['coverage_p10_p90']:.3f} pinball={t['pinball_mean']:.4f} "
          f"monotonicity violations={r['monotonicity']['total_violations']} "
          f"latency={r['latency']['median_ms']:.0f} ms/10k rows\n-> {path}")


if __name__ == "__main__":
    main()
